CREATE TABLE errors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message VARCHAR(4000) NOT NULL,
    state VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    created_at BIGINT NOT NULL
);
CREATE TABLE classification_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    error_id BIGINT NOT NULL UNIQUE REFERENCES errors(id),
    proposed_label VARCHAR(64),
    confidence DOUBLE PRECISION,
    confirmed_label VARCHAR(64),
    failure_reason VARCHAR(64)
);
CREATE TABLE review_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    error_id BIGINT NOT NULL UNIQUE REFERENCES errors(id),
    reason VARCHAR(64) NOT NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'WAITING',
    created_at BIGINT NOT NULL
);
CREATE INDEX idx_review_waiting ON review_queue(state, created_at, id);
